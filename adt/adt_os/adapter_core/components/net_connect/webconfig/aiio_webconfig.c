static int32_t get_Status_handler(aiio_httpd_req_t *req)
{
    if (webconfig_done_s != 0)
    {
        aiio_httpd_resp_send(req, "OK", strlen("OK"));
    }
    else
    {
        aiio_httpd_resp_send(req, "NO", strlen("NO"));
    }

    return 0;
}

// 扫描请求
static int32_t scan_handler(aiio_httpd_req_t *req)
{
    if (scan_init() != AIIO_OK)
    {
        aiio_log_e("scan init failed!!!");
    }

    /* Respond with empty body */
    aiio_httpd_resp_send(req, NULL, 0);

    return 0;
}

static aiio_httpd_handle_t start_webserver(void)
{
    aiio_httpd_handle_t server = NULL;
    aiio_httpd_config_t config = HTTPD_DEFAULT_CONFIG();
    config.server_port = SERVER_PORT;
    config.lru_purge_enable = true;
    config.stack_size = SERVER_STACK;

    // Start the httpd server
    aiio_log_d("Starting server on port: '%d'", config.server_port);
    if (aiio_httpd_start(&server, &config) == AIIO_OK) 
    {
        // Set URI handlers
        aiio_log_d("Registering URI handlers");
        aiio_httpd_register_uri_handler(server, &home);
        aiio_httpd_register_uri_handler(server, &saveInfo);
        aiio_httpd_register_uri_handler(server, &getNetWork);
        aiio_httpd_register_uri_handler(server, &getStatus);
        aiio_httpd_register_uri_handler(server, &scan);

        return server;
    }

    aiio_log_e("Error starting server!");
    return NULL;
}

static int32_t aiio_http_server_init(void)
{
    http_server_handle = start_webserver();
    if (http_server_handle == NULL)
    {
        aiio_log_e("start webserver error!!!");
        return AIIO_ERROR;
    }

    return AIIO_OK;
}

int32_t aiio_webconfig_start(void)
{
    webconfig_done_s = 0;
    webconfig_info_init_s = 0;

    return aiio_http_server_init();
}

int32_t aiio_webconfig_stop(void)
{
    if (ap_ary_p)
    {
        aiio_os_free(ap_ary_p);
        ap_ary_p = NULL;
    }

    int32_t ret = aiio_httpd_stop(http_server_handle);
    if (ret != 0)
    {
        aiio_log_e("httpd stop failed!!!");
        goto __exit;
    }

    http_server_handle = NULL;

__exit:
    return ret;
}

void aiio_webconfig_wifi_event(int32_t evt_code, void *param)
{
    aiio_wifi_sta_connect_ind_stat_info_t stat;

    if (webconfig_info_init_s == 0)
    {
        return;
    }

    switch (evt_code)
    {
    case AIIO_WIFI_EVENT_STA_CONNECTED:
        aiio_log_i("webconfig connected");
        webconfig_done_s = 1;
        if (webconfig_cb)
        {
            aiio_wifi_sta_connect_ind_stat_get(&stat);
            webconfig_cb(stat.ssid, stat.passphr,stat.chan_id);
        }
        break;
    case AIIO_WIFI_EVENT_STA_DISCONNECTED:
        aiio_log_i("webconfig disconnected");
        break;
    case AIIO_WIFI_EVENT_STA_GOT_IP:
        aiio_log_i("webconfig got ip");
        break;
    default:
        aiio_log_d("Unknown code %u", evt_code);
        break;
    }
}

int32_t aiio_webconfig_register_cb(aiio_webconfig_callback_t cb)
{
    webconfig_cb = cb;
    return AIIO_OK;
}
