static void wifi_sta_connect(const char *ssid, const char *pwd, int channel)
{
    aiio_wifi_config_t wifi_sta_config = {
        .sta = {
            .channel = channel,
            .use_dhcp = 1,
            .flags = 0,
        },
    };

    strncpy((char *)wifi_sta_config.sta.ssid, ssid, sizeof(wifi_sta_config.sta.ssid) - 1);
    strncpy((char *)wifi_sta_config.sta.password, pwd, sizeof(wifi_sta_config.sta.password) - 1);

    aiio_log_i("ssid: %s, pwd: %s", wifi_sta_config.sta.ssid, wifi_sta_config.sta.password);

    aiio_wifi_disconnect();
    aiio_wifi_set_mode(AIIO_WIFI_MODE_STA);
    aiio_wifi_set_config(AIIO_WIFI_IF_STA, &wifi_sta_config);
    aiio_wifi_start();

    aiio_log_i("Webconfig start connect Wi-Fi");
}

static int32_t wifi_info_parse(const char *data, web_wifi_info_t *info)
{
    int32_t ret = -1;
    cJSON *Root, *ssid, *password, *mqtt_uri, *mqtt_topic, *mqtt_username, *mqtt_password;

    Root = cJSON_Parse(data);
    if (Root == NULL)
    {
        aiio_log_e("cJSON Parse error!!!");
        goto __exit;
    }

    ssid = cJSON_GetObjectItem(Root, "Network");
    password = cJSON_GetObjectItem(Root, "Password");

    if (ssid == NULL)
    {
        aiio_log_e("ssid is null!!!");
        goto __param_err;
    }

    if (strlen(ssid->valuestring) >= sizeof(info->ssid))
    {
        aiio_log_e("ssid is too long!!!");
        goto __param_err;
    }

    strcpy((char *)info->ssid, ssid->valuestring);

    if (password != NULL)
    {
        if (strlen(password->valuestring) < sizeof(info->pwd))
        {
            strcpy((char *)info->pwd, password->valuestring);
        }
    }

    ret = 0;

__param_err:
    cJSON_Delete(Root);

__exit:
    return ret;
}

static void scan_item_cb(aiio_wifi_ap_item_t *env, uint32_t *param1, aiio_wifi_ap_item_t *item)
{
    uint32_t counter = (*param1);

    /*scan overflow check*/
    if (counter >= WIFI_MGMR_SCAN_ITEMS)
    {
        /*XXX maybe we should warning here*/
        return;
    }
    aiio_wifi_ap_item_t *ap_ary_ptr = (aiio_wifi_ap_item_t *)env + counter; // get and move the ptr to the next item
    counter++;

    /*copy out scan data*/
    ap_ary_ptr->channel = item->channel;
    ap_ary_ptr->rssi = item->rssi;
    memcpy(ap_ary_ptr->bssid, item->bssid, sizeof(ap_ary_ptr->bssid));
    memcpy(ap_ary_ptr->ssid, item->ssid, sizeof(ap_ary_ptr->ssid)); // XXX boundary attack, copy too much data from wifi manager internal?
    ap_ary_ptr->ssid_tail[0] = '\0';
    ap_ary_ptr->ssid_len = strlen((char *)ap_ary_ptr->ssid);
    ap_ary_ptr->auth = item->auth;
    ap_ary_ptr->cipher = item->cipher;

    aiio_log_d("index[%02d]: channel %02u, bssid %02X:%02X:%02X:%02X:%02X:%02X, rssi %3d, auth %d, SSID %s",
               counter,
               ap_ary_ptr->channel,
               ap_ary_ptr->bssid[0],
               ap_ary_ptr->bssid[1],
               ap_ary_ptr->bssid[2],
               ap_ary_ptr->bssid[3],
               ap_ary_ptr->bssid[4],
               ap_ary_ptr->bssid[5],
               ap_ary_ptr->rssi,
               ap_ary_ptr->auth,
               ap_ary_ptr->ssid);
    /*store back counter*/
    (*param1) = counter;
}

static void cb_scan_complete(void *data, void *param)
{
    ap_count = 0;

    aiio_wifi_scan_ap_all(ap_ary_p, &ap_count, scan_item_cb);

    aiio_log_d("cb_scan_complete:%d \r\n", ap_count);
}

static void scan_task(void *param)
{
    (void)(param);

    if (ap_ary_p == NULL)
    {
        ap_ary_p = (aiio_wifi_ap_item_t *)aiio_os_malloc(sizeof(aiio_wifi_ap_item_t) * WIFI_MGMR_SCAN_ITEMS);
        if (ap_ary_p == NULL)
        {
            aiio_log_e("malloc falied");
            goto __exit;
        }

        memset(ap_ary_p, 0, sizeof(aiio_wifi_ap_item_t) * WIFI_MGMR_SCAN_ITEMS);
    }

    aiio_wifi_scan(ap_ary_p, cb_scan_complete, 1);
    
__exit:
    aiio_os_thread_delete(NULL);
}

static int32_t scan_init(void)
{
    return aiio_os_thread_create(NULL, "scan", scan_task, 2048, NULL, 13);
}

